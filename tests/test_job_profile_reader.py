from peacsim.parsing import job_profile_reader
from io import StringIO

# TODO: Add tests covering multihour, force_qos, scale_workload parameters
first_app = "; min_job_power_watts: Least amount of power per node consumed while working on a job" + \
            "\n; max_job_power_watts: Most power consumed per node while working on a job" + \
            "\n; min_time_seconds: Amount of time for the job run without power cap" + \
            "\n; max_time_seconds: Amount of time for the job with the tightest power cap" + \
            "\n; qos_constraint: QoS constraint. Values are generated by random.randint(20, 79)/10." + \
            "\n" + \
            "\n[facesim]" + \
            "\nmin_job_power_watts = 234" + \
            "\nmax_job_power_watts = 276" + \
            "\nmin_time_seconds    = 30.7" + \
            "\nmax_time_seconds    = 35.3" + \
            "\nqos_constraint      = 3.0"

second_app = "\n[bt.D.36]" + \
             "\nmin_job_power_watts = 140" + \
             "\nmax_job_power_watts = 280" + \
             "\nmin_time_seconds = 739" + \
             "\nmax_time_seconds = 1211" + \
             "\nqos_constraint = 5.0" + \
             "\njob_size = 2"

file_one_app = StringIO(first_app)
file_two_app = StringIO(first_app + second_app)

appreader_one_app = job_profile_reader.JobProfileReader(file_one_app)
appreader_two_app = job_profile_reader.JobProfileReader(file_two_app)


def test_all_min_execution_time():
    assert appreader_one_app._all_min_execution_time == {0: 30.7}
    assert appreader_two_app._all_min_execution_time == {0: 30.7, 1: 739}


#   assert appreader.allMinExecutionTime == {0: 30.7, 1: 47.7, 2: 72.7, 3: 52.6}


def test_all_max_execution_time():
    assert appreader_one_app._all_max_execution_time == {0: 35.3}
    assert appreader_two_app._all_max_execution_time == {0: 35.3, 1: 1211}


#   assert appreader.allMaxExecutionTime == {0: 35.3, 1: 50.2, 2: 86.3, 3: 70.3}


def test_all_min_job_power():
    assert appreader_one_app._all_job_power_min == {0: 234}
    assert appreader_two_app._all_job_power_min == {0: 234, 1: 140}


#   assert appreader.allJobPowerMin == {0: 234, 1: 245, 2: 249, 3: 276}


def test_all_max_job_power():
    assert appreader_one_app._all_job_power_max == {0: 276}
    assert appreader_two_app._all_job_power_max == {0: 276, 1: 280}


#   assert appreader.allJobPowerMax == {0: 276, 1: 276, 2: 339, 3: 402}


def test_job_constraints():
    assert appreader_one_app._all_job_qos_constraints == {0: 3.0}
    assert appreader_two_app._all_job_qos_constraints == {0: 3.0, 1: 5.0}


#   assert appreader.allJobQoSConstraints == {0: 3.0, 1: 6.3, 2: 2.5, 3: 4.7}


def test_job_arrival_rate():
    assert appreader_one_app._all_job_arrival_rate == {0: 1}
    assert appreader_two_app._all_job_arrival_rate == {0: 1, 1: 1}


def test_job_size():
    assert appreader_one_app._all_job_size == {0: 1}
    assert appreader_two_app._all_job_size == {0: 1, 1: 2}


def test_all_jobs():
    assert appreader_one_app._all_jobs == {0: 'facesim'}
    assert appreader_two_app._all_jobs == {0: 'facesim', 1: 'bt.D.36'}
